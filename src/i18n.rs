//! Строки интерфейса на двух языках.

use std::fmt::Display;

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
pub enum Lang {
    #[default]
    Ru,
    En,
}

impl Lang {
    pub const ALL: [Self; 2] = [Self::Ru, Self::En];

    pub fn label(self) -> &'static str {
        match self {
            Self::Ru => "Русский",
            Self::En => "English",
        }
    }

    pub fn strings(self) -> &'static Strings {
        match self {
            Self::Ru => &RU,
            Self::En => &EN,
        }
    }
}

/// Подставляет аргументы вместо `{}` по порядку.
pub fn fill(template: &str, args: &[&dyn Display]) -> String {
    let mut out = template.to_owned();
    for arg in args {
        out = out.replacen("{}", &arg.to_string(), 1);
    }
    out
}

pub fn fill1(template: &str, a: impl Display) -> String {
    fill(template, &[&a])
}

pub fn fill2(template: &str, a: impl Display, b: impl Display) -> String {
    fill(template, &[&a, &b])
}

